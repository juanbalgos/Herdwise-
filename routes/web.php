<?php

use App\Http\Controllers\AnimalController;
use App\Http\Controllers\Api\V1\CareActivityController as ApiCareActivityController;
use App\Http\Controllers\Api\V1\LivestockController;
use App\Http\Controllers\Api\V1\ReproductionController as ApiReproductionController;
use App\Http\Controllers\Api\V1\WeightRecordController as ApiWeightRecordController;
use App\Http\Controllers\AuthController;
use App\Http\Controllers\BatchController;
use App\Http\Controllers\CareActivityController;
use App\Http\Controllers\DashboardController;
use App\Http\Controllers\FarmContextController;
use App\Http\Controllers\FarmInvitationController;
use App\Http\Controllers\FarmReportController;
use App\Http\Controllers\FarmTeamController;
use App\Http\Controllers\LivestockIdentificationController;
use App\Http\Controllers\NotificationController;
use App\Http\Controllers\ReproductionController;
use App\Http\Controllers\WeightRecordController;
use Illuminate\Support\Facades\Route;

Route::redirect('/', '/dashboard');
Route::get('/invitations/{token}', [FarmInvitationController::class, 'show'])->where('token', '[A-Za-z0-9]{64}')->middleware('throttle:30,1')->name('invitations.show');
Route::middleware('guest')->group(function () {
    Route::get('/login', [AuthController::class, 'showLogin'])->name('login');
    Route::post('/login', [AuthController::class, 'login'])->name('login.store');
    Route::get('/register', [AuthController::class, 'showRegister'])->name('register');
    Route::post('/register', [AuthController::class, 'register'])->name('register.store');
    Route::get('/register/veterinarian', [AuthController::class, 'showVeterinarianRegistration'])->name('veterinarian.register');
    Route::post('/register/veterinarian', [AuthController::class, 'registerVeterinarian'])->name('veterinarian.register.store');
});
Route::middleware('auth')->group(function () {
    Route::post('/logout', [AuthController::class, 'logout'])->name('logout');
    Route::get('/dashboard', DashboardController::class)->name('dashboard');
    Route::get('/access/waiting', [AuthController::class, 'waitingForAccess'])->name('access.waiting');
    Route::post('/farm-context', [FarmContextController::class, 'update'])->name('farms.context.update');
    Route::post('/invitations/{token}/accept', [FarmInvitationController::class, 'accept'])->where('token', '[A-Za-z0-9]{64}')->middleware('throttle:10,1')->name('invitations.accept');
    Route::get('/team', [FarmTeamController::class, 'index'])->name('team.index');
    Route::post('/team/invitations', [FarmTeamController::class, 'storeInvitation'])->name('team.invitations.store');
    Route::patch('/team/invitations/{invitation}/revoke', [FarmTeamController::class, 'revokeInvitation'])->name('team.invitations.revoke');
    Route::patch('/team/members/{member}/revoke', [FarmTeamController::class, 'revokeMember'])->name('team.members.revoke');
    Route::resource('animals', AnimalController::class)->only(['index', 'create', 'store', 'show', 'edit', 'update']);
    Route::patch('/animals/{animal}/archive', [AnimalController::class, 'archive'])->name('animals.archive');
    Route::patch('/animals/{animal}/restore', [AnimalController::class, 'restore'])->name('animals.restore');
    Route::resource('batches', BatchController::class)->only(['index', 'create', 'store', 'show', 'edit', 'update']);
    Route::patch('/batches/{batch}/archive', [BatchController::class, 'archive'])->name('batches.archive');
    Route::patch('/batches/{batch}/restore', [BatchController::class, 'restore'])->name('batches.restore');
    Route::get('/identify/animals/{animal}', [LivestockIdentificationController::class, 'scanAnimal'])->middleware('signed')->name('identify.animals.scan');
    Route::get('/identify/batches/{batch}', [LivestockIdentificationController::class, 'scanBatch'])->middleware('signed')->name('identify.batches.scan');
    Route::get('/animals/{animal}/qr-code', [LivestockIdentificationController::class, 'animalQrCode'])->name('animals.qr-code');
    Route::get('/animals/{animal}/print-card', [LivestockIdentificationController::class, 'animalPrintCard'])->name('animals.print-card');
    Route::get('/batches/{batch}/qr-code', [LivestockIdentificationController::class, 'batchQrCode'])->name('batches.qr-code');
    Route::get('/batches/{batch}/print-card', [LivestockIdentificationController::class, 'batchPrintCard'])->name('batches.print-card');
    Route::get('/activities', [CareActivityController::class, 'index'])->name('activities.index');
    Route::get('/activities/create/{type}', [CareActivityController::class, 'create'])->name('activities.create');
    Route::post('/activities/health', [CareActivityController::class, 'storeHealth'])->name('activities.health.store');
    Route::post('/activities/treatments', [CareActivityController::class, 'storeTreatment'])->name('activities.treatments.store');
    Route::post('/activities/vaccinations', [CareActivityController::class, 'storeVaccination'])->name('activities.vaccinations.store');
    Route::post('/activities/deworming', [CareActivityController::class, 'storeDeworming'])->name('activities.deworming.store');
    Route::patch('/reminders/{reminder}/complete', [CareActivityController::class, 'completeReminder'])->name('reminders.complete');
    Route::get('/notifications', [NotificationController::class, 'index'])->name('notifications.index');
    Route::patch('/notifications/read-all', [NotificationController::class, 'markAllAsRead'])->name('notifications.read-all');
    Route::patch('/notifications/{notification}/read', [NotificationController::class, 'markAsRead'])->whereUuid('notification')->name('notifications.read');
    Route::get('/reproduction', [ReproductionController::class, 'index'])->name('reproduction.index');
    Route::get('/reproduction/create/{type}', [ReproductionController::class, 'create'])->name('reproduction.create');
    Route::post('/reproduction/breeding', [ReproductionController::class, 'storeBreeding'])->name('reproduction.breeding.store');
    Route::post('/reproduction/pregnancies', [ReproductionController::class, 'storePregnancy'])->name('reproduction.pregnancies.store');
    Route::post('/reproduction/births', [ReproductionController::class, 'storeBirth'])->name('reproduction.births.store');
    Route::get('/weights', [WeightRecordController::class, 'index'])->name('weights.index');
    Route::get('/weights/create', [WeightRecordController::class, 'create'])->name('weights.create');
    Route::post('/weights', [WeightRecordController::class, 'store'])->name('weights.store');
    Route::get('/reports', [FarmReportController::class, 'index'])->name('reports.index');
    Route::get('/reports/export/csv', [FarmReportController::class, 'csv'])->name('reports.csv');
    Route::get('/reports/export/pdf', [FarmReportController::class, 'pdf'])->name('reports.pdf');
    Route::prefix('api/v1')->name('api.v1.')->group(function () {
        Route::get('/animals', [LivestockController::class, 'animals'])->name('animals.index');
        Route::get('/batches', [LivestockController::class, 'batches'])->name('batches.index');
        Route::get('/health-records', [ApiCareActivityController::class, 'healthRecords'])->name('health-records.index');
        Route::get('/reminders', [ApiCareActivityController::class, 'reminders'])->name('reminders.index');
        Route::get('/pregnancies', [ApiReproductionController::class, 'pregnancies'])->name('pregnancies.index');
        Route::get('/weights', [ApiWeightRecordController::class, 'index'])->name('weights.index');
    });
});
